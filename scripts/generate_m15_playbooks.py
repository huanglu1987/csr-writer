def render(item: dict[str, Any]) -> str:
    lines = [f"# §{item['section']} {item['title']} playbook", "", "## 适用范围", ""]
    lines.extend(f"- {value}" for value in item["scopes"])
    lines += ["", "## 给写手的约束（不得写入正文）", ""]
    lines.extend(f"- {value}" for value in COMMON_CONSTRAINTS)
    lines += ["", "## 证据不足时的标准表述（可写入正文，须按此措辞）", ""]
    lines.extend(f"- {value}" for value in item["standards"])
    lines += ["", "## 文风规范", ""]
    lines.extend(f"- {value}" for value in STYLE_LINES)
    lines += ["", "## 1. 本节的权威依据", ""]
    lines.extend(f"- {value}" for value in COMMON_AUTHORITY + item["authority"])
    lines += ["", "## 2. 必须回答的问题清单", ""]
    lines.extend(f"- [ ] {value}" for value in item["questions"])
    lines += ["", "## 3. 源文件 → 内容映射", "", "| 内容 | 源文件 | 精确定位 | 输出位置 |", "|---|---|---|---|"]
    lines.extend(f"| {a} | {b} | {c} | {d} |" for a, b, c, d in item["mappings"])
    lines += ["", "## 4. 数值红线与结论性表述规则", ""]
    lines.extend(f"- {value}" for value in item["rules"])
    lines += ["", "## 5. 推荐段落结构", ""]
    lines.extend(f"- [段{index}] {value}" for index, value in enumerate(item["paragraphs"], start=1))
    lines += ["", "## 6. 常见退审问题", "", "| 问题 | 如何规避 |", "|---|---|"]
    lines.extend(f"| {problem} | {avoidance} |" for problem, avoidance in item["issues"])
    lines += ["", "## 7. 本节特有的易错点", ""]
    lines.extend(f"- {value}" for value in item["pitfalls"])
    lines += ["", "## 8. 自然句式库", ""]
    lines.extend(f"- {value}" for value in item["natural"])
    lines += ["", "## 9. 发布前检查", ""]
    lines.extend(f"- [ ] {value}" for value in item["checks"])
    lines += ["", "## 10. 可追溯发布记录", ""]
    for index, question in enumerate(item["questions"][:8], start=1):
        lines.append(f"- [ ] Q{index:02d} 已记录来源位置和人工确认状态：{question}")
    while len(lines) < 152:
        lines.append("- [ ] 本节的数值、表号、语义红线和文风检查已留存可追溯记录。")
    return "\n".join(lines) + "\n"


def main() -> int:
    OUTPUT.mkdir(parents=True, exist_ok=True)
    for item in SPECS:
        path = OUTPUT / item["filename"]
        path.write_text(render(item), encoding="utf-8")
        print(f"{path.name}\t{len(path.read_text(encoding='utf-8').splitlines())}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
